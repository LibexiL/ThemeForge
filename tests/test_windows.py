def test_spectrum_puts_tones_in_the_right_bars(tf):
    np = pytest.importorskip("numpy")
    sp = tf.Spectrum(32, 48000)
    t = np.arange(sp.n_fft) / 48000
    tone = (0.3 * np.sin(2 * np.pi * 1000 * t)).astype(np.float32)[:, None]
    for _ in range(30):
        vals = sp.process(np.hstack([tone, tone]))
    expected = round(math.log(1000 / 50) / math.log(16000 / 50) * 32 - 0.5)
    assert abs(vals.index(max(vals)) - expected) <= 1 and max(vals) > 0.8
    st = tf.Spectrum(32, 48000, stereo=True)
    bass = np.sin(2 * np.pi * 60 * t).astype(np.float32)[:, None]
    for _ in range(30):
        vals = st.process(np.hstack([bass, bass * 0]))
    assert len(vals) == 32 and vals.index(max(vals)) in (14, 15)         # left bass sits left of center
    for _ in range(300):
        vals = st.process(np.zeros((st.n_fft, 2)))
    assert max(vals) < 0.01                                               # silence falls to nothing


def test_loopback_feed_with_fake_wasapi(tf, monkeypatch, qapp):
    np = pytest.importorskip("numpy")
    opened = {}

    class Stream:
        def __init__(self, **kw):
            opened.update(kw)
            self.t0, self.n = time.monotonic(), 0

        def get_read_available(self):
            return int((time.monotonic() - self.t0) * 48000) - self.n

        def read(self, n, exception_on_overflow=True):
            idx = np.arange(self.n, self.n + n) / 48000
            self.n += n
            x = (0.2 * np.sin(2 * np.pi * 440 * idx)).astype(np.float32)
            return np.repeat(x[:, None], 2, axis=1).tobytes()

        def close(self):
            opened["closed"] = True

    class PyAudio:
        def get_default_wasapi_loopback(self):
            return {"index": 7, "name": "Speakers [Loopback]", "defaultSampleRate": 48000.0, "maxInputChannels": 2}

        def open(self, **kw):
            return Stream(**kw)

        def terminate(self):
            pass

    fake = types.ModuleType("pyaudiowpatch")
    fake.PyAudio, fake.paFloat32 = PyAudio, 1
    monkeypatch.setitem(sys.modules, "pyaudiowpatch", fake)
    feed = tf.LoopbackFeed("test")
    frames = []
    feed.frame.connect(frames.append)
    feed.configure(24, 60, 77, True)
    try:
        assert wait_for(qapp, lambda: len(frames) > 20 and max(frames[-1]) > 0.3)
    finally:
        feed.stop()
    assert all(len(f) == 24 for f in frames) and opened["input_device_index"] == 7 and opened["closed"]
    assert feed.thread is None


