class FakeTimeline:
    def __init__(self, pos, end, updated):
        self.start_time = datetime.timedelta(0)
        self.end_time = datetime.timedelta(seconds=end)
        self.position = datetime.timedelta(seconds=pos)
        self.last_updated_time = updated


class FakeSession:
    def __init__(self, status=4, pos=30, end=200, ago=2.0, title="Song", thumb=b"\x89PNG fake art"):
        self.source_app_user_model_id = "Spotify.exe"
        self.status, self.pos, self.end, self.ago, self.title, self.thumb = status, pos, end, ago, title, thumb
        self.calls = []

    def get_playback_info(self):
        return types.SimpleNamespace(playback_status=self.status)

    def get_timeline_properties(self):
        now = datetime.datetime.now(datetime.timezone.utc)
        return FakeTimeline(self.pos, self.end, now - datetime.timedelta(seconds=self.ago))

    async def try_get_media_properties_async(self):
        thumb = FakeThumb(self.thumb) if self.thumb else None
        return types.SimpleNamespace(title=self.title, artist="Band", album_artist="", album_title="LP",
                                     thumbnail=thumb)

    async def try_toggle_play_pause_async(self):
        self.calls.append("play")

    async def try_skip_next_async(self):
        self.calls.append("next")

    async def try_skip_previous_async(self):
        self.calls.append("prev")

    async def try_change_playback_position_async(self, ticks):
        self.calls.append(("seek", ticks))


class FakeThumb:
    def __init__(self, data):
        self.data = data

    async def open_read_async(self):
        return FakeStream(self.data)


class FakeStream:
    def __init__(self, data):
        self.data, self.size = data, len(data)

    async def read_async(self, buf, size, opt):
        buf[:len(self.data)] = self.data
        return buf


class FakeBuffer(bytearray):
    def __init__(self, size):
        super().__init__(size)

    @property
    def length(self):
        return len(self)


